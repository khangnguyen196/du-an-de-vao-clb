import { beforeEach, describe, expect, it, vi } from 'vitest'
import { describeErrorCause, isAuthError, isBillingError } from '@/lib/ai/structured'
import { AppError, ERROR_CODES } from '@/lib/errors'
import type { Transcript } from '@/types/transcript'

const generateVocabSet = vi.fn()
const hasAnthropicKey = vi.fn()

vi.mock('@/lib/ai/vocabulary', () => ({
  generateVocabSet: (...args: unknown[]) => generateVocabSet(...args),
  hasAnthropicKey: () => hasAnthropicKey(),
}))

const { buildVocabSet } = await import('@/lib/study/vocab-set')

/** Shape copied from the real refusal the API returned for an account with no credit. */
const billingApiError = Object.assign(new Error('Your credit balance is too low to access the Anthropic API.'), {
  statusCode: 400,
  responseBody:
    '{"type":"error","error":{"type":"invalid_request_error","message":"Your credit balance is too low to access the Anthropic API. Please go to Plans & Billing to upgrade or purchase credits."}}',
})

/** Shape recorded from the AI SDK's APICallError for a rejected key (status, message, body). */
const authApiError = Object.assign(new Error('API key is invalid.'), {
  statusCode: 401,
  isRetryable: false,
  responseBody: '{"type":"error","error":{"type":"authentication_error","message":"API key is invalid."},"request_id":null}',
})

let counter = 0
function transcript(): Transcript {
  // A fresh object per test so React's per-call cache never serves a stale result.
  counter += 1
  return {
    source: { kind: 'ted', externalId: `t${counter}`, url: 'https://www.ted.com/talks/t', title: 'T' },
    lang: 'en',
    langLabel: 'English',
    origin: 'captions',
    isAutoGenerated: false,
    cues: [
      { idx: 0, startMs: 0, endMs: 4000, text: 'The methodology was contested across the board.' },
      { idx: 1, startMs: 4000, endMs: 8000, text: 'Resilience turned out to matter more than talent.' },
    ],
    availableTracks: [],
  }
}

describe('isBillingError', () => {
  it('recognises the credit refusal directly and through one level of cause', () => {
    expect(isBillingError(billingApiError)).toBe(true)
    expect(isBillingError(new AppError(ERROR_CODES.AI_FAILED, 'wrapped', { cause: billingApiError }))).toBe(true)
  })

  it('does not mistake other 400s or other failures for billing', () => {
    expect(isBillingError(Object.assign(new Error('x'), { statusCode: 400, responseBody: '{"message":"temperature"}' }))).toBe(false)
    expect(isBillingError(Object.assign(new Error('x'), { statusCode: 402, responseBody: 'credit balance' }))).toBe(false)
    expect(isBillingError(new Error('network'))).toBe(false)
    expect(isBillingError(null)).toBe(false)
  })
})

describe('isAuthError and describeErrorCause', () => {
  it('recognises a rejected key directly, through cause, and through a RetryError', () => {
    expect(isAuthError(authApiError)).toBe(true)
    expect(isAuthError(new AppError(ERROR_CODES.AI_FAILED, 'wrapped', { cause: authApiError }))).toBe(true)
    expect(isAuthError(Object.assign(new Error('retries exhausted'), { lastError: authApiError }))).toBe(true)
  })

  it('does not treat billing or network failures as auth', () => {
    expect(isAuthError(billingApiError)).toBe(false)
    expect(isAuthError(new Error('socket hang up'))).toBe(false)
    expect(isAuthError(null)).toBe(false)
  })

  it('names the innermost API status and message, not the wrapper', () => {
    expect(describeErrorCause(new AppError(ERROR_CODES.AI_FAILED, 'wrapped', { cause: authApiError }))).toBe(
      'HTTP 401: API key is invalid.',
    )
    expect(describeErrorCause(new Error('socket hang up'))).toBeNull()
  })
})

describe('buildVocabSet when the model is unavailable', () => {
  beforeEach(() => {
    generateVocabSet.mockReset()
    hasAnthropicKey.mockReset()
    vi.spyOn(console, 'error').mockImplementation(() => {})
  })

  it('reports no-key without calling the model', async () => {
    hasAnthropicKey.mockReturnValue(false)
    const set = await buildVocabSet(transcript())

    expect(set).toMatchObject({ hasMeanings: false, aiIssue: 'no-key' })
    expect(generateVocabSet).not.toHaveBeenCalled()
  })

  /** The bug this guards: a billing refusal used to take the whole page down with a 500. */
  it('falls back to a real deck and reports billing instead of throwing', async () => {
    hasAnthropicKey.mockReturnValue(true)
    generateVocabSet.mockRejectedValue(new AppError(ERROR_CODES.AI_FAILED, 'no usable set', { cause: billingApiError }))

    const set = await buildVocabSet(transcript())

    expect(set).toMatchObject({ hasMeanings: false, aiIssue: 'billing', model: null })
    expect(set.groups.flatMap((group) => group.items).length).toBeGreaterThan(0)
  })

  /** The page already explains it; an error-level log would flag every vocab view in dev. */
  it('logs no credit as a warning, not an error', async () => {
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {})
    hasAnthropicKey.mockReturnValue(true)
    generateVocabSet.mockRejectedValue(new AppError(ERROR_CODES.AI_FAILED, 'no usable set', { cause: billingApiError }))

    await buildVocabSet(transcript())

    expect(warn.mock.calls.at(-1)?.[0]).toContain('(billing)')
    expect(console.error).not.toHaveBeenCalled()
  })

  /** Reloading cannot fix a rejected key, so the page must not say "try again". */
  it('reports auth when the API rejects the key, and logs the underlying reason', async () => {
    hasAnthropicKey.mockReturnValue(true)
    generateVocabSet.mockRejectedValue(new AppError(ERROR_CODES.AI_FAILED, 'no usable set', { cause: authApiError }))

    expect(await buildVocabSet(transcript())).toMatchObject({ hasMeanings: false, aiIssue: 'auth', model: null })
    expect(vi.mocked(console.error).mock.calls.at(-1)).toContain('— cause: HTTP 401: API key is invalid.')
  })

  it('falls back without calling the model when the per-client limit says no', async () => {
    hasAnthropicKey.mockReturnValue(true)

    const set = await buildVocabSet(transcript(), { allowModel: () => false })

    expect(set).toMatchObject({ hasMeanings: false, aiIssue: 'limited' })
    expect(generateVocabSet).not.toHaveBeenCalled()
  })

  it('does not consult the limit when there is no key — nothing would be spent', async () => {
    hasAnthropicKey.mockReturnValue(false)
    const allowModel = vi.fn(() => false)

    expect(await buildVocabSet(transcript(), { allowModel })).toMatchObject({ aiIssue: 'no-key' })
    expect(allowModel).not.toHaveBeenCalled()
  })

  it('reports a generic failure for anything else', async () => {
    hasAnthropicKey.mockReturnValue(true)
    generateVocabSet.mockRejectedValue(new Error('socket hang up'))

    expect(await buildVocabSet(transcript())).toMatchObject({ hasMeanings: false, aiIssue: 'failed' })
  })

  it('passes a successful set through untouched', async () => {
    hasAnthropicKey.mockReturnValue(true)
    const ok = { groups: [], model: 'claude-sonnet-5', hasMeanings: true }
    generateVocabSet.mockResolvedValue(ok)

    expect(await buildVocabSet(transcript())).toBe(ok)
  })
})

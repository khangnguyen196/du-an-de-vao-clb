import { describe, expect, it } from 'vitest'
import { searchCues } from '@/lib/cues'
import { exportFilename, renderExport } from '@/lib/export'
import type { Transcript } from '@/types/transcript'

/** Invented lines. */
const transcript: Transcript = {
  source: {
    kind: 'ted',
    externalId: 'some_talk',
    url: 'https://www.ted.com/talks/some_talk',
    title: 'Some Talk',
  },
  lang: 'en',
  langLabel: 'English',
  origin: 'captions',
  isAutoGenerated: false,
  cues: [
    { idx: 0, startMs: 1000, endMs: 4000, text: 'The river was cold.', translation: 'Dòng sông lạnh.' },
    // A cue the aligner could not fill.
    { idx: 1, startMs: 4000, endMs: 7000, text: 'Nobody spoke.' },
  ],
  translation: { lang: 'vi', label: 'Tiếng Việt', origin: 'ted', credits: [], coverage: 0.5 },
  availableTracks: [],
}

describe('searchCues with translations', () => {
  it('ignores translations unless they are on screen', () => {
    expect(searchCues(transcript.cues, 'sông')).toEqual([])
  })

  it('finds a word that only appears in the translation when it is shown', () => {
    expect(searchCues(transcript.cues, 'sông', { includeTranslation: true })).toEqual([0])
  })

  it('still finds English text with translations included', () => {
    expect(searchCues(transcript.cues, 'nobody', { includeTranslation: true })).toEqual([1])
  })
})

describe('bilingual export', () => {
  it('keeps monolingual output byte-for-byte unchanged by default', () => {
    expect(renderExport(transcript, 'txt')).toBe('[0:01] The river was cold.\n[0:04] Nobody spoke.')
  })

  it('puts the translation under its line in plain text, aligned past the timestamp', () => {
    expect(renderExport(transcript, 'txt', { bilingual: true })).toBe(
      '[0:01] The river was cold.\n       Dòng sông lạnh.\n\n[0:04] Nobody spoke.',
    )
  })

  it('writes two-line subtitles in SRT, and a single line where no translation exists', () => {
    const srt = renderExport(transcript, 'srt', { bilingual: true })
    expect(srt).toContain('00:00:01,000 --> 00:00:04,000\nThe river was cold.\nDòng sông lạnh.\n')
    expect(srt).toContain('00:00:04,000 --> 00:00:07,000\nNobody spoke.\n')
  })

  it('writes two-line cues in WebVTT', () => {
    expect(renderExport(transcript, 'vtt', { bilingual: true })).toContain(
      '00:00:01.000 --> 00:00:04.000\nThe river was cold.\nDòng sông lạnh.\n',
    )
  })

  it('credits the translation source in Markdown', () => {
    const md = renderExport(transcript, 'md', { bilingual: true })
    expect(md).toContain('_Tiếng Việt: TED_')
    expect(md).toContain('**[0:01]** The river was cold.  \n_Dòng sông lạnh._')
  })

  it('ignores the bilingual flag when the transcript has no translation', () => {
    const plain: Transcript = { ...transcript, translation: undefined }
    expect(renderExport(plain, 'txt', { bilingual: true })).toBe(renderExport(plain, 'txt'))
  })

  it('marks a bilingual file in its name', () => {
    expect(exportFilename(transcript, 'srt', { bilingual: true })).toBe('some-talk.en-vi.srt')
    expect(exportFilename(transcript, 'srt')).toBe('some-talk.srt')
  })
})

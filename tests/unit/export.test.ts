import { describe, expect, it } from 'vitest'
import { exportFilename, renderExport } from '@/lib/export'
import { formatDuration, formatSrtTime, formatTimestamp, formatVttTime } from '@/lib/time'
import type { Transcript } from '@/types/transcript'

const transcript: Transcript = {
  source: {
    kind: 'ted',
    externalId: 'some_talk',
    url: 'https://www.ted.com/talks/some_talk',
    title: 'Sức mạnh của sự tổn thương',
    author: 'Người nói',
    durationMs: 1_202_000,
  },
  lang: 'vi',
  langLabel: 'Tiếng Việt',
  origin: 'captions',
  isAutoGenerated: false,
  cues: [
    { idx: 0, startMs: 1600, endMs: 5085, text: 'Dòng thứ nhất.' },
    { idx: 1, startMs: 5085, endMs: 3_671_500, text: 'Dòng thứ hai.' },
  ],
  availableTracks: [{ code: 'vi', label: 'Tiếng Việt', isAutoGenerated: false }],
}

describe('time formatting', () => {
  it('drops the hour segment under an hour and adds it past one', () => {
    expect(formatTimestamp(65_000)).toBe('1:05')
    expect(formatTimestamp(3_671_500)).toBe('1:01:11')
    expect(formatTimestamp(65_000, { forceHours: true })).toBe('0:01:05')
  })

  it('uses a comma for SRT and a dot for WebVTT', () => {
    expect(formatSrtTime(3_671_500)).toBe('01:01:11,500')
    expect(formatVttTime(3_671_500)).toBe('01:01:11.500')
  })

  it('never renders a negative time', () => {
    expect(formatTimestamp(-500)).toBe('0:00')
  })

  it('formats a duration for the metadata line', () => {
    expect(formatDuration(1_202_000)).toBe('20m 02s')
    expect(formatDuration(3_671_500)).toBe('1h 01m')
  })
})

describe('renderExport', () => {
  it('writes SRT with 1-based indices and an arrow between times', () => {
    const srt = renderExport(transcript, 'srt')
    expect(srt.startsWith('1\n00:00:01,600 --> 00:00:05,085\nDòng thứ nhất.')).toBe(true)
    expect(srt).toContain('\n2\n')
  })

  it('writes a WEBVTT header and dotted times', () => {
    const vtt = renderExport(transcript, 'vtt')
    expect(vtt.startsWith('WEBVTT\n\n')).toBe(true)
    expect(vtt).toContain('00:00:01.600 --> 00:00:05.085')
    expect(vtt).not.toContain(',600 -->')
  })

  it('prefixes each line with a timestamp in text mode', () => {
    expect(renderExport(transcript, 'txt')).toBe('[0:01] Dòng thứ nhất.\n[0:05] Dòng thứ hai.')
  })

  it('omits timestamps when asked for plain prose', () => {
    expect(renderExport(transcript, 'txt', { withTimestamps: false })).toBe(
      'Dòng thứ nhất.\nDòng thứ hai.',
    )
  })

  it('puts the title, author and source link at the top of the Markdown', () => {
    const md = renderExport(transcript, 'md')
    expect(md.startsWith('# Sức mạnh của sự tổn thương')).toBe(true)
    expect(md).toContain('**Người nói**')
    expect(md).toContain('https://www.ted.com/talks/some_talk')
  })
})

describe('exportFilename', () => {
  it('strips Vietnamese diacritics into an ASCII slug', () => {
    expect(exportFilename(transcript, 'srt')).toBe('suc-manh-cua-su-ton-thuong.srt')
  })

  it('falls back to the source id when the title has no usable characters', () => {
    const untitled: Transcript = { ...transcript, source: { ...transcript.source, title: '???' } }
    expect(exportFilename(untitled, 'txt')).toBe('some_talk.txt')
  })
})

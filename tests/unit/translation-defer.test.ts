import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { Cue, Transcript } from '@/types/transcript'

/*
 * The deferred translation is module state (a cache and an in-flight map), so
 * every test starts from a fresh copy of the module and stubs the two things it
 * reaches for: the platform fetch and the model call.
 */

const cues: Cue[] = Array.from({ length: 3 }, (_, idx) => ({
  idx,
  startMs: idx * 1000,
  endMs: idx * 1000 + 1000,
  text: `Line ${idx}.`,
}))

function transcriptOf(overrides: Partial<Transcript> = {}): Transcript {
  return {
    source: { kind: 'ted', externalId: 'a_talk', url: 'https://ted.com/talks/a_talk', title: 'A talk' },
    lang: 'en',
    langLabel: 'English',
    origin: 'captions',
    isAutoGenerated: false,
    cues,
    availableTracks: [],
    ...overrides,
  }
}

const translateCues = vi.fn()
const fetchTedTranscript = vi.fn()

vi.mock('@/lib/ai/translate', () => ({ translateCues: (...args: unknown[]) => translateCues(...args) }))
// Only the network call is stubbed; `parseTedSlug` and the URL helpers are the
// real ones, so a slug that the page would reject here would reject in production.
vi.mock('@/lib/ingest/ted', async (importOriginal) => ({
  ...(await importOriginal<Record<string, unknown>>()),
  fetchTedTranscript: (...args: unknown[]) => fetchTedTranscript(...args),
}))

// The page asks for the client address before anything else (per-client
// limits); outside a request there are no headers, so serve an empty set and
// let the real limiter run with the shared "local" key.
vi.mock('next/headers', () => ({ headers: async () => new Headers() }))

const readStoredTranslation = vi.fn()
vi.mock('@/lib/ingest/translation-store', () => ({
  readStoredTranslation: (...args: unknown[]) => readStoredTranslation(...args),
}))

async function loadModule() {
  vi.resetModules()
  return import('@/lib/ingest/transcript-cache')
}

const answer = { texts: ['Dòng 0.', null, 'Dòng 2.'], translation: { lang: 'vi', label: 'Tiếng Việt', origin: 'model' as const, credits: [], coverage: 2 / 3 } }

let previousKey: string | undefined

beforeEach(() => {
  previousKey = process.env.ANTHROPIC_API_KEY
  process.env.ANTHROPIC_API_KEY = 'sk-ant-test'
  translateCues.mockReset()
  fetchTedTranscript.mockReset()
  readStoredTranslation.mockReset()
  readStoredTranslation.mockReturnValue(null)
})

afterEach(() => {
  if (previousKey === undefined) delete process.env.ANTHROPIC_API_KEY
  else process.env.ANTHROPIC_API_KEY = previousKey
})

describe('needsMachineTranslation', () => {
  it('translates an English talk TED has no human translation for', async () => {
    const { needsMachineTranslation } = await loadModule()
    expect(needsMachineTranslation(transcriptOf())).toBe(true)
  })

  it('leaves a talk alone when the platform already translated it', async () => {
    const { needsMachineTranslation } = await loadModule()
    const withHuman = transcriptOf({
      translation: { lang: 'vi', label: 'Tiếng Việt', origin: 'ted', credits: [], coverage: 1 },
    })
    expect(needsMachineTranslation(withHuman)).toBe(false)
  })

  /** Paying a model to translate Vietnamese into Vietnamese only shows up on the invoice. */
  it.each(['vi', 'VI', 'vi-VN'])('never translates a talk that is already in %s', async (lang) => {
    const { needsMachineTranslation } = await loadModule()
    expect(needsMachineTranslation(transcriptOf({ lang }))).toBe(false)
  })

  it('has nothing to do for an empty transcript', async () => {
    const { needsMachineTranslation } = await loadModule()
    expect(needsMachineTranslation(transcriptOf({ cues: [] }))).toBe(false)
  })
})

describe('getTranscript', () => {
  it('returns the platform transcript without waiting for any model call', async () => {
    const { getTranscript } = await loadModule()
    fetchTedTranscript.mockResolvedValue(transcriptOf())
    translateCues.mockImplementation(() => new Promise(() => {})) // never settles

    const transcript = await getTranscript('a_talk')

    expect(transcript.cues).toHaveLength(3)
    expect(translateCues).not.toHaveBeenCalled()
  })

  it('fetches a talk once and serves the rest from memory', async () => {
    const { getTranscript } = await loadModule()
    fetchTedTranscript.mockResolvedValue(transcriptOf())

    await getTranscript('a_talk')
    await getTranscript('a_talk')

    expect(fetchTedTranscript).toHaveBeenCalledTimes(1)
  })

  /** One slow request must not hide TED's human translation for half an hour. */
  it('refetches soon when the translation failed to load, but not when it was fine', async () => {
    const now = vi.spyOn(Date, 'now')
    try {
      now.mockReturnValue(1_000_000)
      const { getTranscript } = await loadModule()
      fetchTedTranscript.mockResolvedValue(transcriptOf({ translationFetchFailed: true }))
      await getTranscript('a_talk')

      now.mockReturnValue(1_000_000 + 2 * 60 * 1000)
      fetchTedTranscript.mockResolvedValue(transcriptOf())
      await getTranscript('a_talk')
      expect(fetchTedTranscript).toHaveBeenCalledTimes(2)

      now.mockReturnValue(1_000_000 + 4 * 60 * 1000)
      await getTranscript('a_talk')
      expect(fetchTedTranscript).toHaveBeenCalledTimes(2)
    } finally {
      now.mockRestore()
    }
  })
})

describe('getMachineTranslation', () => {
  it('returns null — not a pending promise — when there is nothing to translate', async () => {
    const { getMachineTranslation } = await loadModule()
    const withHuman = transcriptOf({
      translation: { lang: 'vi', label: 'Tiếng Việt', origin: 'ted', credits: [], coverage: 1 },
    })
    expect(getMachineTranslation('a_talk', undefined, withHuman)).toBeNull()
    expect(translateCues).not.toHaveBeenCalled()
  })

  it('returns null when no key is configured, so the page says so instead of waiting', async () => {
    delete process.env.ANTHROPIC_API_KEY
    const { getMachineTranslation } = await loadModule()
    expect(getMachineTranslation('a_talk', undefined, transcriptOf())).toBeNull()
    expect(translateCues).not.toHaveBeenCalled()
  })

  it('serves a translation the translator subagent saved, with no key and no model call', async () => {
    delete process.env.ANTHROPIC_API_KEY
    readStoredTranslation.mockReturnValue(answer)
    const { getMachineTranslation } = await loadModule()

    await expect(getMachineTranslation('a_talk', undefined, transcriptOf())).resolves.toEqual(answer)
    expect(readStoredTranslation).toHaveBeenCalledWith('a_talk', 'en', cues)
    expect(translateCues).not.toHaveBeenCalled()
  })

  /** limits.md: the check happens on the server, before any money is spent. */
  it('skips the model when the per-client limit says no', async () => {
    const { getMachineTranslation } = await loadModule()
    const allowModel = vi.fn(() => false)

    expect(getMachineTranslation('a_talk', undefined, transcriptOf(), { allowModel })).toBeNull()
    expect(allowModel).toHaveBeenCalledTimes(1)
    expect(translateCues).not.toHaveBeenCalled()
  })

  it('does not spend the allowance on a stored translation, which costs nothing', async () => {
    readStoredTranslation.mockReturnValue(answer)
    const { getMachineTranslation } = await loadModule()
    const allowModel = vi.fn(() => false)

    await expect(getMachineTranslation('a_talk', undefined, transcriptOf(), { allowModel })).resolves.toEqual(answer)
    expect(allowModel).not.toHaveBeenCalled()
  })

  it('does not ask again for a run already in flight', async () => {
    const { getMachineTranslation } = await loadModule()
    translateCues.mockImplementation(() => new Promise(() => {}))
    const allowModel = vi.fn(() => true)

    getMachineTranslation('a_talk', undefined, transcriptOf(), { allowModel })
    getMachineTranslation('a_talk', undefined, transcriptOf(), { allowModel })
    expect(allowModel).toHaveBeenCalledTimes(1)
    expect(translateCues).toHaveBeenCalledTimes(1)
  })

  it('never reads a stored file for a talk that needs no translation', async () => {
    const { getMachineTranslation } = await loadModule()
    const withHuman = transcriptOf({
      translation: { lang: 'vi', label: 'Tiếng Việt', origin: 'ted', credits: [], coverage: 1 },
    })

    expect(getMachineTranslation('a_talk', undefined, withHuman)).toBeNull()
    expect(readStoredTranslation).not.toHaveBeenCalled()
  })

  /** Two readers opening the same talk at once must not be billed twice. */
  it('shares one run between concurrent callers', async () => {
    const { getMachineTranslation } = await loadModule()
    let release: (value: typeof answer) => void = () => {}
    translateCues.mockReturnValue(new Promise<typeof answer>((resolve) => (release = resolve)))

    const first = getMachineTranslation('a_talk', undefined, transcriptOf())
    const second = getMachineTranslation('a_talk', undefined, transcriptOf())

    expect(translateCues).toHaveBeenCalledTimes(1)
    release(answer)
    await expect(first).resolves.toEqual(answer)
    await expect(second).resolves.toEqual(answer)
  })

  it('serves a finished translation from cache without calling the model again', async () => {
    const { getMachineTranslation } = await loadModule()
    translateCues.mockResolvedValue(answer)

    await getMachineTranslation('a_talk', undefined, transcriptOf())
    await getMachineTranslation('a_talk', undefined, transcriptOf())

    expect(translateCues).toHaveBeenCalledTimes(1)
  })

  it('keys the cache by language, so ?lang=fr is not served the English run', async () => {
    const { getMachineTranslation } = await loadModule()
    translateCues.mockResolvedValue(answer)

    await getMachineTranslation('a_talk', undefined, transcriptOf())
    await getMachineTranslation('a_talk', 'fr', transcriptOf({ lang: 'fr' }))

    expect(translateCues).toHaveBeenCalledTimes(2)
  })

  /*
   * A page streams until this settles. A failure that escaped here would take
   * down a page whose transcript was already rendered and correct.
   */
  it('resolves to null instead of rejecting when the model call fails', async () => {
    const error = vi.spyOn(console, 'error').mockImplementation(() => {})
    const { getMachineTranslation } = await loadModule()
    translateCues.mockRejectedValue(new Error('credit balance is too low'))

    await expect(getMachineTranslation('a_talk', undefined, transcriptOf())).resolves.toBeNull()
    expect(error).toHaveBeenCalled()
    error.mockRestore()
  })

  it('does not retry a failed talk on the very next view', async () => {
    const error = vi.spyOn(console, 'error').mockImplementation(() => {})
    const { getMachineTranslation } = await loadModule()
    translateCues.mockRejectedValue(new Error('boom'))

    await getMachineTranslation('a_talk', undefined, transcriptOf())
    expect(getMachineTranslation('a_talk', undefined, transcriptOf())).toBeNull()

    expect(translateCues).toHaveBeenCalledTimes(1)
    error.mockRestore()
  })

  it('gives up rather than holding the page stream open forever', async () => {
    vi.useFakeTimers()
    const error = vi.spyOn(console, 'error').mockImplementation(() => {})
    const { getMachineTranslation } = await loadModule()
    translateCues.mockReturnValue(new Promise(() => {})) // a call that never answers

    const pending = getMachineTranslation('a_talk', undefined, transcriptOf())
    await vi.advanceTimersByTimeAsync(120 * 1000)

    await expect(pending).resolves.toBeNull()
    expect(error).toHaveBeenCalledWith(expect.stringContaining('timed out'))
    error.mockRestore()
    vi.useRealTimers()
  })
})

describe('getTranslatedTranscript', () => {
  it('merges the translation in for callers that cannot be sent one later', async () => {
    const { getTranslatedTranscript } = await loadModule()
    fetchTedTranscript.mockResolvedValue(transcriptOf())
    translateCues.mockResolvedValue(answer)

    const transcript = await getTranslatedTranscript('a_talk')

    expect(transcript.cues[0]!.translation).toBe('Dòng 0.')
    expect(transcript.cues[1]!.translation).toBeUndefined()
    expect(transcript.cues[2]!.translation).toBe('Dòng 2.')
    expect(transcript.translation).toMatchObject({ origin: 'model' })
  })

  it('still returns the transcript when the translation fails', async () => {
    const error = vi.spyOn(console, 'error').mockImplementation(() => {})
    const { getTranslatedTranscript } = await loadModule()
    fetchTedTranscript.mockResolvedValue(transcriptOf())
    translateCues.mockRejectedValue(new Error('boom'))

    const transcript = await getTranslatedTranscript('a_talk')

    expect(transcript.cues).toHaveLength(3)
    expect(transcript.translation).toBeUndefined()
    error.mockRestore()
  })
})

/**
 * The point of the whole arrangement, guarded directly: the page must hand back
 * its markup while the model is still working. If someone re-adds an `await` in
 * front of `getMachineTranslation`, this is what fails.
 */
/*
 * Each test here re-imports the whole page and its component tree from cold
 * (`vi.resetModules`). That takes about a second alone and can pass 5 s when
 * the full suite runs in parallel, so these get more room. A real wait on the
 * translation would hang forever, not take 6 s, so this hides nothing.
 */
describe('the watch page does not wait for the translation', { timeout: 30_000 }, () => {
  const single: Cue[] = [{ idx: 0, startMs: 0, endMs: 1000, text: 'Hello.' }]

  /** The page renders JSON-LD next to the view; the props under test are the view's. */
  function watchView(element: unknown): { props: Record<string, unknown> } {
    const root = element as { props: { children?: unknown; transcript?: unknown } }
    if (root.props.transcript !== undefined) return root as { props: Record<string, unknown> }
    const children = ([] as unknown[]).concat(root.props.children ?? [])
    const view = children.find(
      (child) => (child as { props?: { transcript?: unknown } } | null)?.props?.transcript !== undefined,
    )
    if (!view) throw new Error('WatchView not found in the page output')
    return view as { props: Record<string, unknown> }
  }

  /** Resolves to 'pending' when `promise` has not settled by the next few ticks. */
  async function stateOf(promise: Promise<unknown>): Promise<'pending' | 'settled'> {
    const marker = Symbol('pending')
    const result = await Promise.race([promise.then(() => 'settled' as const), Promise.resolve(marker)])
    return result === marker ? 'pending' : 'settled'
  }

  it('returns the transcript view with the translation still in flight', async () => {
    vi.resetModules()
    fetchTedTranscript.mockResolvedValue(transcriptOf({ cues: single }))
    translateCues.mockReturnValue(new Promise(() => {})) // still working

    const { default: WatchPage } = await import('@/app/(app)/watch/ted/[slug]/page')
    const element = watchView(
      await WatchPage({
        params: Promise.resolve({ slug: 'a_talk' }),
        searchParams: Promise.resolve({}),
      }),
    ) as { props: { transcript: Transcript; machineTranslation: Promise<unknown> | null } }

    expect(translateCues).toHaveBeenCalledTimes(1)
    expect(element.props.transcript.cues).toHaveLength(1)
    expect(element.props.machineTranslation).toBeInstanceOf(Promise)
    await expect(stateOf(element.props.machineTranslation!)).resolves.toBe('pending')
  })

  it('passes no promise at all when there is nothing to translate, so the view says so', async () => {
    vi.resetModules()
    fetchTedTranscript.mockResolvedValue(
      transcriptOf({
        cues: single,
        translation: { lang: 'vi', label: 'Tiếng Việt', origin: 'ted', credits: [], coverage: 1 },
      }),
    )

    const { default: WatchPage } = await import('@/app/(app)/watch/ted/[slug]/page')
    const element = watchView(
      await WatchPage({
        params: Promise.resolve({ slug: 'a_talk' }),
        searchParams: Promise.resolve({}),
      }),
    ) as { props: { machineTranslation: Promise<unknown> | null } }

    expect(element.props.machineTranslation).toBeNull()
    expect(translateCues).not.toHaveBeenCalled()
  })
})

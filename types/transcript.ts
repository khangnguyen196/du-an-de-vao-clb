export type SourceKind = 'youtube' | 'ted' | 'upload'
export type TranscriptOrigin = 'captions' | 'whisper' | 'manual'
export type TranscriptStatus = 'pending' | 'processing' | 'ready' | 'failed'

/**
 * Smallest unit of a transcript. Every study feature (summary, flashcard,
 * quiz, chat) must reference a cue so the content stays traceable.
 * All times are milliseconds — never seconds.
 */
export interface Cue {
  idx: number
  startMs: number
  endMs: number
  text: string
  speaker?: string
  /**
   * Translation of this line, when one exists. Absent rather than empty when
   * nothing was aligned here, so the UI never renders a blank line as if it
   * were a translation.
   */
  translation?: string
}

export type TranslationOrigin = 'ted' | 'model'

export interface TranslationCredit {
  role: 'translator' | 'reviewer'
  name: string | null
  url: string
}

export interface TranscriptTranslation {
  lang: string
  label: string
  /** "ted" = human translation from the platform; "model" = machine output. */
  origin: TranslationOrigin
  /**
   * Translator and reviewer as credited by the platform. TED exposes a profile
   * link but not always a name, so `name` stays null rather than being guessed.
   */
  credits: TranslationCredit[]
  /** Share of cues that received a translation, 0–1. */
  coverage: number
}

export interface CaptionTrack {
  /** BCP-47-ish code as reported by the platform, e.g. "en", "vi", "en-GB". */
  code: string
  label: string
  isAutoGenerated: boolean
}

export interface TranscriptSource {
  kind: SourceKind
  externalId: string
  url: string
  title: string
  author?: string
  durationMs?: number
  thumbnailUrl?: string
  /**
   * The platform's own HLS stream, without any intro bumper, so playback time
   * and cue times share one clock. Absent when the platform offers none — the
   * page then falls back to the official embed, which reports no position.
   */
  streamUrl?: string
}

export interface Transcript {
  source: TranscriptSource
  lang: string
  langLabel: string
  origin: TranscriptOrigin
  isAutoGenerated: boolean
  cues: Cue[]
  /** Present only when a translation was found and aligned onto the cues. */
  translation?: TranscriptTranslation
  /**
   * The platform's translation could not be fetched this time (timeout, network)
   * — as opposed to the talk simply having none. Transient: a cache should not
   * keep a transcript carrying this for long, or one slow request hides a human
   * translation for the whole cache lifetime.
   */
  translationFetchFailed?: true
  availableTracks: CaptionTrack[]
}
